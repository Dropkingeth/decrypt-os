def backup_path(path):
    """path.bak-<UTC timestamp>, with a -N suffix when that name is taken."""
    base = path.with_name(f'{path.name}.bak-{time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())}')
    candidate, n = base, 1
    while os.path.lexists(candidate):
        candidate, n = base.with_name(f'{base.name}-{n}'), n + 1
    return candidate


def add_login_plan(ctx, args):
    """(actions, info) for add-login; raises Refused. Nothing is changed here."""
    login_id = args.login_id
    if not LOGIN_ID_RE.match(login_id):
        raise Refused(f'login id must match {LOGIN_ID_RE.pattern[:-2]}$')
    registry_path = Path(os.path.abspath(os.path.expanduser(args.logins))) if args.logins else ctx.root / LOGINS_NAME
