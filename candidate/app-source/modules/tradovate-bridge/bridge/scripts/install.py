def cmd_uninstall(ctx, args):
    have_systemctl = shutil.which('systemctl') is not None
    present = [n for n in UNITS if os.path.lexists(ctx.unit_path(n))]
    foreign = [n for n in present if MARKER not in (ctx.unit_path(n).read_text() if ctx.unit_path(n).is_file() else '')]
    if foreign:
        print(f'uninstall refused: {", ".join(foreign)} not written by this tool; handle by hand', file=sys.stderr)
        return 1
    if have_systemctl:
        for name in STOP_ORDER:
            state = unit_state(name)
            if is_active(state):
                print(f'stopping {name}')
                systemctl('stop', name)
                if is_active(unit_state(name)):
                    print(f'uninstall stopped: {name} is still active; nothing removed', file=sys.stderr)
                    return 1
            if state is not None and state[1] in ('enabled', 'enabled-runtime', 'linked', 'linked-runtime'):
                print(f'disabling {name}')
                systemctl('disable', name)
    elif present:
        print('systemctl not available; make sure the units are not running')
    for name in present:
        ctx.unit_path(name).unlink()
        print(f'removed {ctx.unit_path(name)}')
    if present and have_systemctl:
        systemctl('daemon-reload')
    if ctx.current.is_symlink():
        ctx.current.unlink()
        fsync_dir(ctx.root)
        print(f'removed {ctx.current} (symlink)')
    elif os.path.lexists(ctx.current):
        print(f'left {ctx.current} alone: not a symlink')
    if ctx.root.is_dir() and not os.path.lexists(ctx.kill):
        write_new(ctx.kill, '', 0o600)
        print(f'restored kill switch {ctx.kill}')
    kept = [p for p in (ctx.releases, ctx.journal, ctx.config, ctx.env, ctx.kill) if os.path.lexists(p)]
    print('kept: ' + (', '.join(str(p) for p in kept) or 'nothing else existed'))
    count, _ = journal_report(ctx)
    if count:
        print(f'WARNING: journal has {count} unresolved command(s); reconcile before switching Soup back.')
    return 0


def cmd_rollback(ctx, args):
    target, cur, problems = current_release(ctx)
    if cur is None:
        print('rollback refused: no verified current release ' + ('; '.join(problems) if problems else
              '(nothing installed; use install)'), file=sys.stderr)
        return 1
    count, msgs = journal_report(ctx)
    if count is None or count:
        print(f'rollback refused: journal has {"unreadable" if count is None else count} unresolved command(s). '
              f'Reconcile first: python3 -m tvbridge.reconcile --journal-dir {ctx.journal} --list', file=sys.stderr)
        for m in msgs:
            print(f'  {m}', file=sys.stderr)
        return 1
    release, rproblems = check_release(ctx, resolve_release_arg(ctx, args.release))
    if release is None or rproblems:
        print('rollback refused: release failed verification', file=sys.stderr)
        for p in rproblems:
            print(f'  - {p}', file=sys.stderr)
        return 1
    if version_key(release.version) >= version_key(cur.version):
        print(f'rollback refused: {release.version} is not older than current {cur.version}; use install',
              file=sys.stderr)
        return 1
    new_target = os.path.relpath(release.path.resolve(), ctx.root.resolve())
    if not os.path.lexists(ctx.kill):
        write_new(ctx.kill, '', 0o600)
        print(f'restored kill switch {ctx.kill}')
    point_current(ctx, new_target)
    print(f'current: {target} -> {new_target} (version {cur.version} -> {release.version})')
    print('Units run from current/, so they were not rewritten. If the daemon is running:')
    print(f'  systemctl --user restart {DAEMON_UNIT}')
    print(f'Kill switch {KILL_NAME} is present. Removing it again is your decision.')
    return 0

