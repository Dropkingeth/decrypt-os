class Refused(Exception):
    pass


def default_unit_dir():
    base = os.environ.get('XDG_CONFIG_HOME') or os.path.join(os.path.expanduser('~'), '.config')
    return os.path.join(base, 'systemd', 'user')


def version_key(v):
    return tuple(int(x) for x in re.findall(r'\d+', str(v)))


def mode_of(path):
    return stat.S_IMODE(os.lstat(path).st_mode)


def fsync_dir(path):
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def write_new(path, data, mode):
    """Create a file that must not exist yet (O_EXCL): never overwrites."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    try:
        os.fchmod(fd, mode)
        os.write(fd, data.encode())
        os.fsync(fd)
    finally:
        os.close(fd)
    fsync_dir(path.parent)


def write_replace(path, data, mode):
    tmp = path.with_name(f'.{path.name}.tmp-{os.getpid()}')
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    try:
        os.fchmod(fd, mode)
        os.write(fd, data.encode())
        os.fsync(fd)
    finally:
        os.close(fd)
    os.replace(tmp, path)
    fsync_dir(path.parent)


def read_env_file(path):
    values = {}
    for line in Path(path).read_text().splitlines():
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, value = line.split('=', 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in '"\'':
            value = value[1:-1]
        values[key.strip()] = value
    return values


def load_json(path):
    try:
        return json.loads(Path(path).read_text()), None
    except FileNotFoundError:
        return None, 'missing'
    except (OSError, ValueError) as exc:
        return None, f'unreadable ({type(exc).__name__})'


class Ctx:
    def __init__(self, args):
        self.root = Path(os.path.abspath(os.path.expanduser(args.root)))
        self.unit_dir = Path(os.path.abspath(os.path.expanduser(args.unit_dir)))
        self.profile = Path(os.path.abspath(os.path.expanduser(args.profile_dir)))
        self.chromium = Path(os.path.abspath(os.path.expanduser(args.chromium)))
        self.python = Path(os.path.abspath(os.path.expanduser(args.python)))
        self.releases = self.root / 'releases'
        self.current = self.root / 'current'
        self.journal = self.root / 'journal'
        self.config = self.root / 'config.json'
        self.env = self.root / ENV_NAME
        self.kill = self.root / KILL_NAME
        self.args = args

    def unit_path(self, name):
        return self.unit_dir / name

    def cli(self, script, sub, extra=''):
        """Copy-pasteable command for this tool with the same non-default options."""
        parts = ['python3', str(script), sub]
        for flag, value, default in (('--root', self.root, DEFAULT_ROOT),
                                     ('--unit-dir', self.unit_dir, default_unit_dir()),
                                     ('--profile-dir', self.profile, os.path.expanduser(DEFAULT_PROFILE)),
                                     ('--chromium', self.chromium, DEFAULT_CHROMIUM),
                                     ('--python', self.python, DEFAULT_PYTHON)):
            if str(value) != os.path.abspath(os.path.expanduser(default)):
                parts += [flag, str(value)]
        cmd = ' '.join(shlex.quote(p) for p in parts)
        return cmd + (' ' + extra if extra else '')

    def journal_dirs(self):
        dirs = [self.journal]
        cfg, _ = load_json(self.config)
        if isinstance(cfg, dict) and isinstance(cfg.get('journal_dir'), str):
            configured = Path(os.path.abspath(cfg['journal_dir']))
            if configured != self.journal:
                dirs.append(configured)
        return dirs


# ---------------------------------------------------------------- releases

class Release:
    def __init__(self, path, manifest, notes):
        self.path = path
        self.manifest = manifest
        self.version = manifest['version']
        self.name = path.name
        self.notes = notes

    def installer(self):
        own = self.path / 'scripts' / 'install.py'
        return own if own.is_file() else Path(__file__).resolve()


def resolve_release_arg(ctx, arg):
    if arg is None:
        latest = ctx.releases / 'LATEST'
        if not latest.is_file():
            raise Refused('no --release given and no releases/LATEST')
        arg = latest.read_text().strip()
        for cand in (ctx.releases / arg, ctx.releases / ('tvbridge-' + arg)):
            if cand.is_dir():
                return Path(os.path.abspath(cand))
        raise Refused(f'releases/LATEST names {arg!r}, which is not an extracted release directory')
    p = Path(os.path.expanduser(arg))
    if not p.is_absolute() and not p.exists():
        for cand in (ctx.releases / arg, ctx.releases / ('tvbridge-' + arg)):
            if cand.exists():
                p = cand
                break
    return Path(os.path.abspath(p))


def check_release(ctx, path):
    """Verify an extracted release. Returns (Release or None, problems)."""
    if not path.is_dir():
        return None, [f'release directory not found: {path}']
    problems = []
    if path.resolve().parent != ctx.releases.resolve():
        problems.append(f'release must be a directory directly inside {ctx.releases}')
    try:
        manifest, mismatches = verify_release.check(path)
        if not isinstance(manifest.get('files'), dict) or not isinstance(manifest.get('version'), str):
            raise ValueError('manifest shape')
    except (OSError, ValueError, KeyError, AttributeError) as exc:
        return None, problems + [f'MANIFEST.json unusable ({type(exc).__name__})']
    problems += mismatches
    if manifest.get('name') != 'tvbridge':
        problems.append('manifest name is not tvbridge')
    if path.name != 'tvbridge-' + manifest['version']:
        problems.append(f'directory name {path.name} does not match manifest version {manifest["version"]}')
    for rel in REQUIRED_RELEASE_FILES:
        if rel not in manifest['files']:
            problems.append(f'release lacks {rel}')
    links = sorted(str(p.relative_to(path)) for p in path.rglob('*') if p.is_symlink())
    problems += [f'symlink inside release: {n}' for n in links]
    notes = []
    tarball = path.parent / (path.name + '.tar.gz')
    sums = path.parent / (path.name + '.tar.gz.sha256')
    if tarball.is_file():
        digest = hashlib.sha256(tarball.read_bytes()).hexdigest()
        if sums.is_file():
            expected = sums.read_text().split()[0] if sums.read_text().split() else ''
            if expected != digest:
                problems.append(f'{tarball.name} does not match {sums.name}')
            else:
                notes.append('archive sha256 matches')
        else:
            notes.append('no .sha256 beside the archive')
        try:
            with tarfile.open(tarball) as tar:
                member = tar.extractfile(f'{path.name}/MANIFEST.json')
                archived = member.read() if member else None
        except (OSError, tarfile.TarError, KeyError):
            archived = None
        if archived is None:
            problems.append(f'{tarball.name} has no readable MANIFEST.json')
        elif archived != (path / 'MANIFEST.json').read_bytes():
            problems.append('extracted MANIFEST.json differs from the archive copy')
        else:
            notes.append('extracted manifest matches the archive')
    else:
        notes.append('no archive beside the release; checked against its own MANIFEST.json only')
    return Release(path, manifest, notes), problems


def current_release(ctx):
    """(target_text, Release or None, problems) for the current symlink; (None, None, []) if absent."""
    if not os.path.lexists(ctx.current):
        return None, None, []
    if not ctx.current.is_symlink():
        return None, None, [f'{ctx.current} exists but is not a symlink']
    target = os.readlink(ctx.current)
    rel, problems = check_release(ctx, Path(os.path.abspath(ctx.root / target)))
    return target, rel, problems


# ---------------------------------------------------------------- journal

def journal_report(ctx):
    """(unresolved count or None when unreadable, messages)."""
    total, messages = 0, []
    for d in ctx.journal_dirs():
        if not d.is_dir():
            continue
        try:
            j = Journal(d)  # existing directory: Journal does not create or modify anything
            n = len(j.unresolved())
        except Exception as exc:  # noqa: BLE001 - any unreadable journal must block
            messages.append(f'journal {d} unreadable ({type(exc).__name__})')
            return None, messages
        total += n
        if j.torn_tail:
            messages.append(f'journal {d} has a torn last line (crash mid-append)')
    return total, messages


# ---------------------------------------------------------------- config and units

def new_config_text(ctx, release):
    cfg = json.loads((release.path / 'config.example.json').read_text())
    cfg['kill_switch_file'] = str(ctx.kill)
    cfg['journal_dir'] = str(ctx.journal)
    return json.dumps(cfg, indent=2) + '\n'


def effective_config(ctx, release):
    if os.path.lexists(ctx.config):
        cfg, err = load_json(ctx.config)
        if cfg is None or not isinstance(cfg, dict):
            raise Refused(f'{ctx.config} is {err or "not a JSON object"}; fix it by hand (install never overwrites it)')
        return cfg
    return json.loads(new_config_text(ctx, release))


def port_value(cfg, key):
    v = cfg.get(key)
    if isinstance(v, bool) or not isinstance(v, int) or not 1 <= v <= 65535:
        raise Refused(f'config {key} must be an integer port')
    return v


def unit_texts(ctx, cfg):
    devtools = port_value(cfg, 'devtools_port')
    listen = port_value(cfg, 'listen_port')
    for key, port in (('devtools_port', devtools), ('listen_port', listen)):
        if port in RESERVED_PORTS:
            raise Refused(f'config {key} {port} is reserved (never use {sorted(RESERVED_PORTS)})')
    for label, p in (('root', ctx.root), ('profile dir', ctx.profile), ('chromium', ctx.chromium),
                     ('python', ctx.python)):
        if not SAFE_PATH_RE.match(str(p)):
            raise Refused(f'{label} path {p} has characters systemd would reinterpret; use a plain path')
    if ctx.chromium.name != 'chromium':
        raise Refused('launch-browser.sh selects the binary named "chromium" on PATH; --chromium must end in /chromium')
    search = ':'.join(dict.fromkeys([str(ctx.chromium.parent), '/usr/local/bin', '/usr/bin', '/bin']))
    browser = f"""{MARKER}
[Unit]
Description=Tradovate bridge dedicated Chromium (loopback DevTools {devtools})
After=graphical-session.target
PartOf=graphical-session.target

[Service]
Type=simple
Environment=TVBRIDGE_DEVTOOLS_PORT={devtools}
Environment=TVBRIDGE_PROFILE={ctx.profile}
Environment=TVBRIDGE_PASSWORD_STORE=gnome-libsecret
Environment=PATH={search}
ExecStart=/bin/sh {ctx.current}/scripts/launch-browser.sh
Restart=no
UMask=0077

[Install]
WantedBy=graphical-session.target
"""
    daemon = f"""{MARKER}
[Unit]
Description=Tradovate bridge daemon (loopback {listen}, DevTools {devtools})
After={BROWSER_UNIT}
StartLimitIntervalSec=600
StartLimitBurst=3

[Service]
Type=simple
WorkingDirectory={ctx.current}
EnvironmentFile={ctx.env}
Environment=PYTHONDONTWRITEBYTECODE=1
Environment=PYTHONUNBUFFERED=1
ExecStart={ctx.python} -m tvbridge.daemon --config {ctx.config}
Restart=on-failure
RestartSec=30
UMask=0077
NoNewPrivileges=yes

[Install]
WantedBy=default.target
"""
    return {BROWSER_UNIT: browser, DAEMON_UNIT: daemon}


def env_text():
    return ('# tvbridge daemon environment. Mode 0600. Never commit, copy or print.\n'
            f'TVBRIDGE_TOKEN={secrets.token_urlsafe(32)}\n'
            '# SOUP_BROKER_TOKEN is needed only for publish_mode "soup":\n'
            '# SOUP_BROKER_TOKEN=\n')


# ---------------------------------------------------------------- install plan

def plan_actions(ctx, release):
    """Ordered (verb, path, detail, do) tuples plus blockers. plan prints them; install runs them."""
    actions, blockers = [], []

    def add(verb, path, detail, do=None):
        actions.append((verb, str(path), detail, do))

    if ctx.root.is_dir():
        add('keep', ctx.root, 'directory exists')
    else:
        add('create', ctx.root, 'directory, mode 0700', lambda: (ctx.root.mkdir(parents=True, mode=0o700),
                                                                 os.chmod(ctx.root, 0o700)))

    # The kill switch goes first so no step ever runs with entries enabled by default.
    if os.path.lexists(ctx.kill):
        add('keep', ctx.kill, 'kill switch present; install never removes it')
    else:
        add('create', ctx.kill, 'kill switch (entries disabled), mode 0600',
            lambda: write_new(ctx.kill, '', 0o600))

    if ctx.journal.is_dir():
        add('keep', ctx.journal, f'exists (mode {mode_of(ctx.journal):04o})')
    elif os.path.lexists(ctx.journal):
        blockers.append(f'{ctx.journal} exists and is not a directory')
    else:
        add('create', ctx.journal, 'directory, mode 0700', lambda: (os.mkdir(ctx.journal, 0o700),
                                                                    os.chmod(ctx.journal, 0o700)))

    if os.path.lexists(ctx.config):
        add('keep', ctx.config, 'exists; never overwritten')
    else:
        add('create', ctx.config, 'mode 0600 from the release config.example.json, with journal_dir and '
            'kill_switch_file set under root; placeholders stay until you edit them',
            None if release is None else
            (lambda t=new_config_text(ctx, release): write_new(ctx.config, t, 0o600)))

    if os.path.lexists(ctx.env):
        add('keep', ctx.env, 'exists; never overwritten')
    else:
        add('create', ctx.env, 'mode 0600 with a freshly generated TVBRIDGE_TOKEN (not shown)',
            lambda: write_new(ctx.env, env_text(), 0o600))

    if release is None:  # plan only: show the layout, install refuses without a verified release
        add('link', ctx.current, '-> releases/tvbridge-<version> (needs a verified release)')
        for name in UNITS:
            add('write', ctx.unit_path(name), 'unit rendered once a release is selected')
        return actions, blockers, {}

    target = os.path.relpath(release.path.resolve(), ctx.root.resolve())
    if not os.path.lexists(ctx.current):
        add('link', ctx.current, f'-> {target} (atomic)', lambda t=target: point_current(ctx, t))
    elif not ctx.current.is_symlink():
        blockers.append(f'{ctx.current} exists and is not a symlink; move it aside by hand')
    elif os.readlink(ctx.current) == target:
        add('keep', ctx.current, f'-> {target}')
    else:
        old = os.readlink(ctx.current)
        count, msgs = journal_report(ctx)
        if count is None or count:
            blockers.append(f'journal has {"unreadable" if count is None else count} unresolved command(s); '
                            'reconcile with python3 -m tvbridge.reconcile before changing releases')
            blockers += msgs
        add('relink', ctx.current, f'{old} -> {target} (atomic)', lambda t=target: point_current(ctx, t))

    try:
        texts = unit_texts(ctx, effective_config(ctx, release))
    except Refused as exc:
        blockers.append(str(exc))
        texts = {}
    if texts and not ctx.unit_dir.is_dir():
        add('create', ctx.unit_dir, 'systemd user unit directory',
            lambda: ctx.unit_dir.mkdir(parents=True, exist_ok=True))
    for name, text in texts.items():
        path = ctx.unit_path(name)
        if not os.path.lexists(path):
            add('write', path, 'new unit (not enabled, not started)',
                lambda p=path, t=text: write_replace(p, t, 0o644))
        else:
            existing = path.read_text() if path.is_file() else ''
            if MARKER not in existing:
                blockers.append(f'{path} exists and was not written by this tool; move it aside by hand')
            elif existing == text:
                add('keep', path, 'unit unchanged')
            else:
                add('replace', path, 'regenerated unit (not enabled, not started)',
                    lambda p=path, t=text: write_replace(p, t, 0o644))
    return actions, blockers, texts


def point_current(ctx, target):
    tmp = ctx.root / f'.current.tmp-{os.getpid()}'
    if os.path.lexists(tmp):
        os.unlink(tmp)
    os.symlink(target, tmp)
    os.replace(tmp, ctx.current)
    fsync_dir(ctx.root)


def print_actions(actions):
    width = max(len(a[1]) for a in actions) if actions else 0
    for verb, path, detail, _ in actions:
        print(f'  {verb:<8} {path:<{width}}  {detail}')


def print_next_steps(ctx, release):
    cli = lambda sub, extra='': ctx.cli(release.installer(), sub, extra)  # noqa: E731
    print('\nNothing was enabled or started. Operator steps, after review:')
    print(f'  1. Edit {ctx.config}: account_name, soup_account_id, ticker, ports. Keep publish_mode "evidence".')
    print(f'  2. If you changed devtools_port or listen_port, refresh the units: '
          f'{cli("install", "--release " + shlex.quote(str(release.path)))}')
    print(f'  3. {cli("preflight")}')
    print('  4. systemctl --user daemon-reload')
    print(f'  5. systemctl --user start {BROWSER_UNIT}    # then log in to Tradovate by hand in that window')
    print(f'  6. systemctl --user start {DAEMON_UNIT}')
    print(f'  7. {cli("status")}')
    print(f'  Optional, start at login: systemctl --user enable {BROWSER_UNIT} {DAEMON_UNIT}')
    print(f'  {KILL_NAME} stays in place. Removing it is your decision.')
    print(f'  Disable everything: {cli("uninstall")}')


# ---------------------------------------------------------------- subcommands

def cmd_plan(ctx, args):
    try:
        release, problems = check_release(ctx, resolve_release_arg(ctx, args.release))
    except Refused as exc:
        release, problems = None, [str(exc)]
    print('tvbridge install plan (nothing is changed)')
    print(f'  root:     {ctx.root}')
    print(f'  unit dir: {ctx.unit_dir}')
    if release is None:
        print(f'  release:  none usable (extract one into {ctx.releases}/ and pass --release)')
    else:
        print(f'  release:  {release.path} (version {release.version}, {len(release.manifest["files"])} files; '
              f'{"; ".join(release.notes)})')
    actions, blockers, texts = plan_actions(ctx, release)
    blockers = problems + blockers
    print('\nActions:')
    print_actions(actions)
    print('  (no systemctl command is run; units are not enabled or started)')
    for verb, path, _, _ in actions:
        name = Path(path).name
        if verb in ('write', 'replace') and name in texts:
            print(f'\n--- {path} ---\n{texts[name]}', end='')
    if blockers:
        print('\ninstall would REFUSE:')
        for b in blockers:
            print(f'  - {b}')
        return 1
    print(f'\nTo apply: {ctx.cli(Path(__file__).resolve(), "install", "--release " + shlex.quote(str(release.path)))}')
    return 0


def cmd_install(ctx, args):
    release, problems = check_release(ctx, resolve_release_arg(ctx, args.release))
    if release is None or problems:
        print('install refused: release failed verification', file=sys.stderr)
        for p in problems:
            print(f'  - {p}', file=sys.stderr)
        return 1
    actions, blockers, _ = plan_actions(ctx, release)
    if blockers:
        print('install refused:', file=sys.stderr)
        for b in blockers:
            print(f'  - {b}', file=sys.stderr)
        return 1
    print(f'release {release.name} verified ({"; ".join(release.notes)})')
    for verb, path, detail, do in actions:
        if do is not None:
            do()
    print_actions(actions)
    if all(a[3] is None for a in actions):
        print('already installed; nothing changed')
    print_next_steps(ctx, release)
    return 0


def systemctl(*args):
    """(returncode, stdout) or None when systemctl is not available."""
    exe = shutil.which('systemctl')
    if not exe:
        return None
    try:
        p = subprocess.run([exe, '--user', *args], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError) as exc:
        return 255, f'error ({type(exc).__name__})'
    return p.returncode, p.stdout.strip().splitlines()[0] if p.stdout.strip() else ''


def unit_state(name):
    active = systemctl('is-active', name)
    if active is None:
        return None
    enabled = systemctl('is-enabled', name)
    return active[1] or 'unknown', enabled[1] or 'unknown'


def is_active(state):
    return state is not None and state[0] in ('active', 'activating', 'reloading', 'deactivating')


def port_in_use(port):
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind(('127.0.0.1', port))
    except OSError:
        return True
    finally:
        s.close()
    return False


def pid_alive(pid):
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def profile_users(profile):
    """(in-use reasons, warnings) for a Chromium user-data-dir."""
    users, warnings = [], []
    lock = profile / 'SingletonLock'
    if os.path.islink(lock):
        host, _, pid = os.readlink(lock).rpartition('-')
        if not pid.isdigit():
            warnings.append('profile SingletonLock has an unexpected format')
        elif host != socket.gethostname():
            users.append(f'profile SingletonLock names another host ({host})')
        elif pid_alive(int(pid)):
            users.append(f'profile SingletonLock held by running pid {pid}')
        else:
            warnings.append(f'stale profile SingletonLock (pid {pid} not running)')
    real = os.path.realpath(profile)
    proc = Path('/proc')
    if proc.is_dir():
        for d in proc.glob('[0-9]*'):
            if d.name == str(os.getpid()):
                continue
            try:
                argv = (d / 'cmdline').read_bytes().split(b'\0')
            except OSError:
                continue
            for arg in argv:
                if arg.startswith(b'--user-data-dir='):
                    path = os.fsdecode(arg.split(b'=', 1)[1])
                    if os.path.realpath(os.path.expanduser(path)) == real:
                        users.append(f'process {d.name} runs with this --user-data-dir')
    return users, warnings


def cmd_preflight(ctx, args):
    fails, warns, oks = [], [], []
    ok, fail, warn = oks.append, fails.append, warns.append

    target, release, problems = current_release(ctx)
    if release is None and not problems:
        fail(f'{ctx.current} missing; run install first')
    elif problems:
        fail(f'current release failed verification: {"; ".join(problems[:5])}')
    else:
        ok(f'current -> {target} verified (version {release.version})')

    cfg, err = load_json(ctx.config)
    if not isinstance(cfg, dict):
        fail(f'config {ctx.config} {err or "is not a JSON object"}')
        cfg = None
    else:
        if mode_of(ctx.config) != 0o600:
            fail(f'config mode is {mode_of(ctx.config):04o}, expected 0600')
        missing = [k for k in REQUIRED_CONFIG_KEYS if k not in cfg]
        if missing:
            fail(f'config lacks {", ".join(missing)}')
        example = None
        if release is not None:
            example, _ = load_json(release.path / 'config.example.json')
        placeholders = []
        for key in ('account_name', 'soup_account_id', 'ticker'):
            if not isinstance(cfg.get(key), str) or not cfg.get(key, '').strip():
                placeholders.append(key)
        for key, value in cfg.items():
            if isinstance(value, str) and PLACEHOLDER_RE.search(value):
                placeholders.append(key)
            if isinstance(example, dict) and key in ('account_name', 'soup_account_id') \
                    and value == example.get(key):
                placeholders.append(key)
        if placeholders:
            fail('config has placeholder or empty values: ' + ', '.join(sorted(set(placeholders))))
        else:
            ok('config has no placeholder values')
        mode = cfg.get('publish_mode')
        if mode not in ('evidence', 'soup', 'adapter-db'):
            fail('config publish_mode must be "evidence", "soup" or "adapter-db"')
        elif mode == 'soup':
            warn('publish_mode is "soup": snapshots go to Soup')
        elif mode == 'adapter-db':
            # 1.0.6: the Soup primary-route cutover. Soup reads this database as its broker adapter.
            if not all(isinstance(cfg.get(k), str) and cfg[k].startswith('/')
                       for k in ('soup_adapter_db', 'soup_context_path')):
                fail('publish_mode "adapter-db" needs absolute soup_adapter_db and soup_context_path')
            else:
                warn('publish_mode is "adapter-db": Soup reads bridge evidence as its broker adapter')
        if cfg.get('account_view_enabled', False) not in (True, False):
            fail('config account_view_enabled must be true or false')
        if cfg.get('followers'):
            # 1.0.7 firing order: the daemon refuses to start on an invalid followers block.
            try:
                from tvbridge import followers as follower_accounts
                enabled = [key for key, _, on in follower_accounts.parse(cfg) if on]
            except ValueError as exc:
                fail(f'config followers: {exc}')
            else:
                warn('followers configured (firing order): '
                     + (', '.join(enabled) if enabled else 'none enabled'))
                native = [key for key, ecfg, on in follower_accounts.parse(cfg) if on and ecfg.get('native_exits_enabled')]
                if native:
                    warn('native exits on followers (1.0.8; brackets, flatten_all, auto-protect): ' + ', '.join(native))
        if cfg.get('kill_switch_file') != str(ctx.kill):
            fail(f'config kill_switch_file must be {ctx.kill}')
        if cfg.get('journal_dir') != str(ctx.journal):
            warn(f'config journal_dir is not {ctx.journal}; status and rollback check both')

    if os.path.lexists(ctx.kill):
        ok(f'kill switch {KILL_NAME} present (entries disabled)')
    else:
        fail(f'kill switch {ctx.kill} missing; create it (touch) before enabling')

    if not ctx.env.is_file():
        fail(f'env file {ctx.env} missing; run install')
    else:
        if mode_of(ctx.env) != 0o600:
            fail(f'env file mode is {mode_of(ctx.env):04o}, expected 0600')
        env = read_env_file(ctx.env)
        if len(env.get('TVBRIDGE_TOKEN', '')) < 24:
            fail('env file TVBRIDGE_TOKEN missing or shorter than 24 characters')
        else:
            ok('env file has TVBRIDGE_TOKEN (not shown)')
        if cfg and cfg.get('publish_mode') == 'soup' and len(env.get('SOUP_BROKER_TOKEN', '')) < 24:
            fail('publish_mode "soup" needs SOUP_BROKER_TOKEN (24+ characters) in the env file')

    if not ctx.journal.is_dir():
        fail(f'journal directory {ctx.journal} missing; run install')
    elif mode_of(ctx.journal) != 0o700:
        fail(f'journal directory mode is {mode_of(ctx.journal):04o}, expected 0700')
    count, msgs = journal_report(ctx)
    for m in msgs:
        (fail if count is None else warn)(m)
    if count:
        fail(f'journal has {count} unresolved command(s); run python3 -m tvbridge.reconcile '
             f'--journal-dir {ctx.journal} --list')
    elif count == 0:
        ok('journal has no unresolved commands')

    if cfg:
        ports = {}
        for key in ('devtools_port', 'listen_port'):
            v = cfg.get(key)
            if isinstance(v, bool) or not isinstance(v, int) or not 1 <= v <= 65535:
                fail(f'config {key} is not a valid port')
            elif v in RESERVED_PORTS:
                fail(f'config {key} {v} is reserved (never {sorted(RESERVED_PORTS)}); not probed')
            else:
                ports[key] = v
        if len(ports) == 2 and ports['devtools_port'] == ports['listen_port']:
            fail('devtools_port and listen_port must differ')
        soup_port = re.match(r'^https?://[^/:]+:(\d+)', str(cfg.get('soup_base_url', '')))
        for key, v in ports.items():
            if soup_port and v == int(soup_port.group(1)):
                fail(f'config {key} {v} is Soup\'s port from soup_base_url')
            elif port_in_use(v):
                fail(f'config {key} {v} is already in use on 127.0.0.1')
            else:
                ok(f'{key} {v} is free')

    states = {}
    for name in UNITS:
        path = ctx.unit_path(name)
        if not path.is_file():
            fail(f'unit {path} missing; run install')
        states[name] = unit_state(name)
        if is_active(states[name]):
            fail(f'{name} is already {states[name][0]}; preflight is for before start (use status)')
    if release is not None and cfg:
        try:
            texts = unit_texts(ctx, cfg)
            stale = [n for n, t in texts.items() if ctx.unit_path(n).is_file() and ctx.unit_path(n).read_text() != t]
            if stale:
                fail(f'unit(s) {", ".join(stale)} do not match config/options; rerun install to regenerate')
            elif all(ctx.unit_path(n).is_file() for n in texts):
                ok('unit files match config and options')
        except Refused as exc:
            fail(str(exc))
    if all(s is None for s in states.values()):
        warn('systemctl not available; unit state not checked')

    if ctx.chromium.is_file() and os.access(ctx.chromium, os.X_OK):
        ok(f'chromium present at {ctx.chromium}')
    else:
        fail(f'chromium not found or not executable at {ctx.chromium}')
    if ctx.python.is_file() and os.access(ctx.python, os.X_OK):
        ok(f'python present at {ctx.python}')
    else:
        fail(f'python not found or not executable at {ctx.python}')

    shared = [os.path.realpath(os.path.expanduser(p)) for p in ('~/.config/chromium', '~/.config/google-chrome')]
    if os.path.realpath(ctx.profile) in shared:
        fail(f'profile {ctx.profile} is a default browser profile; use a dedicated one')
    users, pwarns = profile_users(ctx.profile)
    for w in pwarns:
        warn(w)
    if users:
        fail(f'profile {ctx.profile} is in use: {"; ".join(users)}')
    else:
        ok(f'profile {ctx.profile} not in use by a running browser')

    for m in oks:
        print(f'OK    {m}')
    for m in warns:
        print(f'WARN  {m}')
    for m in fails:
        print(f'FAIL  {m}')
    if fails:
        print(f'\npreflight FAILED: {len(fails)} problem(s). Do not start the units.')
        return 1
    print('\npreflight passed. Start the units with the systemctl --user commands that install printed.')
    return 0


def health_probe(port, token):
    """Summary of GET /health/<token> on loopback; the token never appears in the result."""
    conn = http.client.HTTPConnection('127.0.0.1', port, timeout=3)
    try:
        conn.request('GET', '/health/' + token)
        resp = conn.getresponse()
        body = resp.read(65536).decode('utf-8', 'replace')
    except (OSError, http.client.HTTPException) as exc:
        return f'unreachable ({type(exc).__name__})'
    finally:
        conn.close()
    if resp.status != 200:
        return f'HTTP {resp.status}'
    try:
        data = json.loads(body)
        summary = json.dumps({'health': data.get('health'), 'entries_disabled': data.get('entries_disabled')},
                             sort_keys=True)
    except (ValueError, AttributeError):
        summary = 'unparseable response'
    return 'HTTP 200 ' + summary.replace(token, '<redacted>')


