#!/usr/bin/env python3
"""Install lifecycle for the Tradovate bridge on a Linux host with systemd user units.

  install.py plan      [--release DIR]  show exactly what install would do; changes nothing
  install.py install   --release DIR    verify the release, point current/ at it, create missing data
                                        files, write (not enable, not start) the user units
  install.py preflight                  checks to run before starting the units; exit 1 on any failure
  install.py status                     release, units, kill switch, health, journal
  install.py uninstall                  stop/disable/remove the units and current/; keep all data
  install.py rollback  --release DIR    point current/ at an older verified release
  install.py add-login ID [--dry-run]   add a separate Tradovate login (1.1.0 multi-login): logins/ID/,
                                        a logins.json entry and the primary's peer_logins; starts nothing

Every subcommand takes --root, --unit-dir, --profile-dir, --chromium and --python.
This tool never enables or starts a unit and never prints a secret. Stdlib only.
"""
